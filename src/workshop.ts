/**
 * Canonical Workshop backend (https://github.com/canonical/workshop), driven through the
 * `workshop` CLI. Workshop creates and manages the LXD container (or VM) itself.
 *
 * Workshop always mounts its own project directory read-write at /project, so pion does not
 * use the user's project as the workshop project. Instead it keeps a private workshop
 * project per user project, under the state directory, containing:
 *
 *   workshop.yaml              name, base, runtime and SDKs from pion's config
 *   .workshop/pion/sdk.yaml    an in-project SDK with one mount plug, "project"
 *
 * The plug targets the guest path, optionally read-only, and pion points it at the user's
 * project with `workshop remount`. This keeps workshop's `.workshop.lock` and definitions
 * out of the user's repository, and makes read-only possible.
 *
 * Facts this relies on (verified against workshop 0.9.9 with lxd-container):
 * - A read-only mount plug cannot be written, even by root in the container; remount is denied.
 * - Files written by the `workshop` user (uid 1000) appear on the host owned by the host
 *   user; files written by root appear as an unprivileged mapped uid.
 * - Remounting a populated directory requires the workshop to be stopped. The remount
 *   survives `refresh`, `stop` and `start`, but not `remove`.
 * - `refresh` applies plug changes such as read-only on a ready workshop.
 * - Killing the local `workshop exec` client, or its `--timeout`, does not stop the guest
 *   process, so commands run in their own session and are killed by process group.
 */

import { spawn } from "node:child_process";
import { createHash, randomUUID } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import type { BackendInfo, ExecOptions, ExecResult, Progress, SandboxBackend } from "./backend.ts";
import type { SandboxConfig } from "./config.ts";
import { KILL_GROUP_SCRIPT, probeGuest, runCli, runClient, runSetupOnce, SESSION_WRAPPER, SessionRegistry } from "./shared.ts";

/** The in-project SDK pion adds, and its mount plug. */
const PION_SDK = "pion";
const PLUG = "project";
/** Workshop's fixed unprivileged user. */
const WORKSHOP_UID = 1000;
const WORKSHOP_GID = 1000;
const WORKSHOP_HOME = "/home/workshop";
const NOSUDO_FILE = "/etc/sudoers.d/zz-pion-nosudo";

export interface WorkshopInfo {
	status: string;
	runtime?: string;
	/** Host source of pion's project plug, with `~` expanded. */
	hostSource?: string;
	/** Guest target of pion's project plug. */
	workshopTarget?: string;
}

/** Parse the YAML printed by `workshop info`. Only the fields pion needs are extracted. */
export function parseWorkshopInfo(text: string, home = os.homedir()): WorkshopInfo {
	const expand = (v: string) => (v === "~" ? home : v.startsWith("~/") ? path.join(home, v.slice(2)) : v);
	const info: WorkshopInfo = { status: "" };
	// Track the key path by indentation.
	const stack: Array<{ indent: number; key: string }> = [];
	for (const line of text.split("\n")) {
		const m = /^(\s*)([^\s:][^:]*):\s*(.*)$/.exec(line);
		if (!m) continue;
		const indent = m[1]!.length;
		const key = m[2]!.trim();
		const value = m[3]!.trim();
		while (stack.length > 0 && stack[stack.length - 1]!.indent >= indent) stack.pop();
		const keyPath = [...stack.map((s) => s.key), key].join(".");
		if (keyPath === "status") info.status = value.toLowerCase();
		else if (keyPath === "runtime") info.runtime = value;
		else if (keyPath === `sdks.${PION_SDK}.mounts.${PLUG}.host-source`) info.hostSource = expand(value);
		else if (keyPath === `sdks.${PION_SDK}.mounts.${PLUG}.workshop-target`) info.workshopTarget = value;
		if (value === "") stack.push({ indent, key });
	}
	return info;
}

const q = (v: string) => JSON.stringify(v);

/** Render the private project's workshop definition and pion's in-project SDK. */
export function renderDefinitions(cfg: SandboxConfig): { workshopYaml: string; sdkYaml: string } {
	const w = cfg.workshop;
	const lines = ["# Generated by pion; edits are overwritten.", `name: ${w.name}`, `base: ${q(w.base)}`];
	// Only emit the runtime key when it differs from workshop's default, for older releases.
	if (w.runtime !== "lxd-container") lines.push(`runtime: ${q(w.runtime)}`);
	lines.push("sdks:", `  - name: project-${PION_SDK}`);
	for (const sdk of w.sdks) {
		lines.push(`  - name: ${q(sdk.name)}`);
		if (sdk.channel) lines.push(`    channel: ${q(sdk.channel)}`);
	}
	const sdkYaml = [
		"# Generated by pion; edits are overwritten.",
		`name: ${PION_SDK}`,
		"summary: Mount point for the pion project",
		"plugs:",
		`  ${PLUG}:`,
		"    interface: mount",
		`    workshop-target: ${q(cfg.guestPath)}`,
		`    read-only: ${cfg.mount === "ro"}`,
		`    uid: ${WORKSHOP_UID}`,
		`    gid: ${WORKSHOP_GID}`,
		"",
	].join("\n");
	return { workshopYaml: `${lines.join("\n")}\n`, sdkYaml };
}

function canonical(p: string): string {
	try {
		return realpathSync(p);
	} catch {
		return path.resolve(p);
	}
}

export class WorkshopBackend implements SandboxBackend {
	private readonly cfg: SandboxConfig;
	/** pion's private workshop project directory. */
	readonly projectRoot: string;
	private info: BackendInfo | undefined;
	private released = false;
	private readonly sessions: SessionRegistry;

	constructor(cfg: SandboxConfig) {
		this.cfg = cfg;
		this.projectRoot = path.join(cfg.workshop.stateDir, cfg.workshop.name);
		this.sessions = new SessionRegistry("workshop", this.projectRoot, cfg.workshop.name);
	}

	private get name(): string {
		return this.cfg.workshop.name;
	}

	private cli(sub: string, args: string[] = []): Promise<{ code: number | null; stdout: string; stderr: string }> {
		return runCli(this.cfg.workshop.cli, [sub, "-p", this.projectRoot, ...args]);
	}

	private async cliOk(sub: string, args: string[], what: string): Promise<string> {
		const r = await this.cli(sub, args);
		if (r.code !== 0) throw new Error(`${what} failed: ${(r.stderr || r.stdout).trim() || `exit ${r.code}`}`);
		return r.stdout;
	}

	/** Write the definition files; returns a digest of their contents. */
	private writeDefinitions(): string {
		const { workshopYaml, sdkYaml } = renderDefinitions(this.cfg);
		const sdkDir = path.join(this.projectRoot, ".workshop", PION_SDK);
		mkdirSync(sdkDir, { recursive: true });
		const write = (file: string, content: string) => {
			if (!existsSync(file) || readFileSync(file, "utf8") !== content) writeFileSync(file, content);
		};
		write(path.join(this.projectRoot, "workshop.yaml"), workshopYaml);
		write(path.join(sdkDir, "sdk.yaml"), sdkYaml);
		write(
			path.join(this.projectRoot, "README.txt"),
			`pion's private workshop project for ${this.cfg.projectDir}.\nThe project itself is mounted at ${this.cfg.guestPath} via the "${PION_SDK}:${PLUG}" plug.\n`,
		);
		return createHash("sha256").update(workshopYaml).update(sdkYaml).digest("hex");
	}

	private get appliedFile(): string {
		return path.join(this.projectRoot, ".pion-applied");
	}

	private appliedDigest(): string | undefined {
		try {
			return readFileSync(this.appliedFile, "utf8").trim();
		} catch {
			return undefined;
		}
	}

	private async getInfo(): Promise<WorkshopInfo | undefined> {
		const r = await this.cli("info", [this.name]);
		if (r.code !== 0) {
			if (/not launched/i.test(r.stderr)) return undefined;
			throw new Error(`workshop info failed: ${(r.stderr || r.stdout).trim()}`);
		}
		return parseWorkshopInfo(r.stdout);
	}

	/** Run as root without the session wrapper, for provisioning. */
	private rootExec(argv: string[]): Promise<{ code: number | null; stdout: string; stderr: string }> {
		return this.cli("exec", ["-I", "--uid", "0", "--gid", "0", "--cwd", "/", this.name, "--", ...argv]);
	}

	private userExec(argv: string[]): Promise<{ code: number | null; stdout: string; stderr: string }> {
		return this.cli("exec", ["-I", "--uid", String(WORKSHOP_UID), "--gid", String(WORKSHOP_GID), "--cwd", WORKSHOP_HOME, this.name, "--", ...argv]);
	}

	async start(progress: Progress): Promise<BackendInfo> {
		if (this.info) return this.info;
		this.released = false;
		const w = this.cfg.workshop;
		const digest = this.writeDefinitions();

		let info = await this.getInfo();
		if (!info) {
			progress(`launching workshop ${this.name} (${w.base}${w.sdks.length ? `, ${w.sdks.map((s) => s.name).join(", ")}` : ""})`);
			await this.cliOk("launch", [this.name], `launching workshop ${this.name}`);
			writeFileSync(this.appliedFile, digest);
			info = await this.getInfo();
			if (!info) throw new Error(`workshop ${this.name} is not launched after launch`);
		} else {
			if (info.runtime && info.runtime !== w.runtime) {
				throw new Error(
					`workshop ${this.name} runs on ${info.runtime} but the config asks for ${w.runtime}; the runtime is fixed at launch. ` +
						`Remove it with: workshop remove -p ${this.projectRoot} ${this.name}`,
				);
			}
			if (info.status === "stopped") {
				progress(`starting workshop ${this.name}`);
				await this.cliOk("start", [this.name], `starting workshop ${this.name}`);
				info.status = "ready";
			}
			if (info.status !== "ready") {
				throw new Error(`workshop ${this.name} is ${info.status || "in an unknown state"}; check: workshop info -p ${this.projectRoot} ${this.name}`);
			}
			if (this.appliedDigest() !== digest) {
				progress(`refreshing workshop ${this.name}`);
				await this.cliOk("refresh", [this.name], `refreshing workshop ${this.name}`);
				writeFileSync(this.appliedFile, digest);
				info = (await this.getInfo()) ?? info;
			}
		}

		// Point the plug at the real project. A populated source needs the workshop stopped.
		if (!info.hostSource || canonical(info.hostSource) !== canonical(this.cfg.projectDir)) {
			progress(`mounting ${this.cfg.projectDir} (${this.cfg.mount})`);
			await this.cliOk("stop", [this.name], `stopping workshop ${this.name}`);
			await this.cliOk("remount", [`${this.name}/${PION_SDK}:${PLUG}`, this.cfg.projectDir], "remounting the project");
			await this.cliOk("start", [this.name], `starting workshop ${this.name}`);
		}

		const check = await this.userExec(["test", "-d", this.cfg.guestPath]);
		if (check.code !== 0) {
			const infoText = (await this.cli("info", [this.name])).stdout.trim();
			const mounts = (await this.rootExec(["sh", "-c", "grep -v -e cgroup -e proc -e sysfs -e tmpfs /proc/mounts"])).stdout.trim();
			throw new Error(
				`project mount ${this.cfg.guestPath} is missing inside workshop ${this.name} (${check.stderr.trim() || `exit ${check.code}`})\n` +
					`workshop info:\n${infoText}\nguest mounts:\n${mounts}`,
			);
		}

		this.sessions.register(this.cfg.projectDir);

		// Workshop grants its user passwordless sudo; a later sudoers file can deny it. The last
		// matching rule wins, and `workshop exec` itself sudoes from workshop to workshop, so
		// that case stays allowed while running as any other user is denied.
		const sudo = this.cfg.sudo
			? await this.rootExec(["rm", "-f", NOSUDO_FILE])
			: await this.rootExec([
					"sh",
					"-c",
					`printf '%s\\n' 'workshop ALL=(ALL:ALL) !ALL' 'workshop ALL=(workshop:workshop) NOPASSWD: ALL' > ${NOSUDO_FILE} && chmod 0440 ${NOSUDO_FILE} && visudo -cq`,
				]);
		if (sudo.code !== 0) throw new Error(`configuring sudo failed: ${sudo.stderr.trim()}`);

		await runSetupOnce(this.cfg, (argv) => this.rootExec(argv), progress);
		const { shell, hasRipgrep } = await probeGuest((argv) => this.userExec(argv));

		const runtimeLabel = w.runtime === "lxd-vm" ? "LXD VM" : "LXD container";
		this.info = {
			kind: "workshop",
			label: `workshop ${this.name} (${this.cfg.mount})`,
			details: [
				`Backend: workshop ${this.name} (${runtimeLabel}, ${w.base})`,
				`SDKs: ${w.sdks.length ? w.sdks.map((s) => (s.channel ? `${s.name}/${s.channel}` : s.name)).join(", ") : "none"}`,
				`Mount: ${this.cfg.projectDir} -> ${this.cfg.guestPath} (${this.cfg.mount === "ro" ? "read-only" : "writable"})`,
				`Guest user: workshop (uid ${WORKSHOP_UID}), home ${WORKSHOP_HOME}${this.cfg.sudo ? ", passwordless sudo" : ", no sudo"}`,
				`Shell: ${shell}; ripgrep: ${hasRipgrep ? "yes" : "no (using grep/find)"}`,
				`Workshop project: ${this.projectRoot}`,
				`On exit: ${w.onExit}`,
			],
			shell,
			hasRipgrep,
		};
		return this.info;
	}

	exec(argv: string[], options: ExecOptions = {}): Promise<ExecResult> {
		if (!this.info && !options.asRoot) return Promise.reject(new Error("sandbox is not started"));
		const pidfile = `/tmp/.pion-${randomUUID()}.pid`;
		const root = Boolean(options.asRoot);
		const env: Record<string, string> = {
			LANG: "C.UTF-8",
			...(root ? { HOME: "/root", USER: "root", LOGNAME: "root" } : { HOME: WORKSHOP_HOME, USER: "workshop", LOGNAME: "workshop" }),
			...this.cfg.env,
			...options.env,
			PION_PIDFILE: pidfile,
		};
		const args = ["exec", "-p", this.projectRoot, "-I", "--uid", String(root ? 0 : WORKSHOP_UID), "--gid", String(root ? 0 : WORKSHOP_GID)];
		args.push("--cwd", options.cwd ?? this.cfg.guestPath);
		// "NAME" without "=" would inherit from the host environment; always pass a value.
		for (const [k, v] of Object.entries(env)) args.push("--env", `${k}=${v}`);
		args.push(this.name, "--", "setsid", "-w", "sh", "-c", SESSION_WRAPPER, "sh", ...argv);
		return runClient(this.cfg.workshop.cli, args, options, async () => {
			await this.rootExec(["sh", "-c", KILL_GROUP_SCRIPT, "sh", pidfile]);
		});
	}

	async shutdown(progress: Progress, reason: "quit" | "switch"): Promise<void> {
		if (this.released) return;
		this.released = true;
		const wasStarted = this.info !== undefined;
		this.info = undefined;
		const others = this.sessions.unregister();
		const policy = this.cfg.workshop.onExit;
		if (reason !== "quit" || policy === "keep" || !wasStarted) return;
		if (others > 0) {
			progress(`leaving workshop ${this.name} running for ${others} other pi session(s)`);
			return;
		}
		const sub = policy === "delete" ? "remove" : "stop";
		progress(`${policy === "delete" ? "removing" : "stopping"} workshop ${this.name}`);
		// Detached so pi can exit while the workshop shuts down.
		const child = spawn(this.cfg.workshop.cli, [sub, "-p", this.projectRoot, this.name], { detached: true, stdio: "ignore" });
		child.on("error", () => {});
		child.unref();
	}

	async stop(): Promise<void> {
		this.info = undefined;
		const r = await this.cli("stop", [this.name]);
		if (r.code !== 0 && !/already stopped|not started|stopped/i.test(r.stderr)) throw new Error(`stopping workshop ${this.name} failed: ${r.stderr.trim()}`);
	}
}
